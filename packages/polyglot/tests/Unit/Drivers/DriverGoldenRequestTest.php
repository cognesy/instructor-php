/**
 * Pins the WIRE OUTPUT of every bundled driver: the URL, headers and decoded body each one
 * produces for a fixed set of requests, plus the capabilities it reports (instructor-eexl.9).
 *
 * Landed BEFORE seventeen driver classes were replaced by declarative specs. The fixture is
 * the evidence that the replacement changed nothing, so it must not be regenerated by that
 * work. Any diff afterwards is a regression, not a rebaseline.
 *
 * The request is captured through MockHttpDriver rather than by reaching into the protected
 * toHttpRequest(), so what is pinned is what the driver would actually have sent.
 *
 * WHY SEVEN REQUESTS AND NOT ONE. The first version of this test used a single request and was
 * worse than useless: several drivers' *only* difference from plain OpenAI sits on a branch
 * that request never took, so the pin would have gone on passing while a spec refactor erased
 * them. The variants below were not guessed -- every method in the Drivers tree was
 * instrumented with an execution counter and the snapshot re-run, and each variant exists to
 * close a specific gap that measurement exposed. See the table in
 * research/plans/polyglot-improvements/measurements/eexl-9-driver-specs.md.
 *
 * Worth keeping even if the spec refactor is abandoned: nothing else in this package asserts
 * that a given provider name produces a given payload, which is the one thing every user of
 * it depends on.
 */
const DRIVER_GOLDEN_FIXTURE = __DIR__ . '/../../Fixtures/driver-golden-requests.json';

